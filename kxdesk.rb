class Kxdesk < Formula
  desc "Personal desktop daemon for SketchyBar, yabai and friends"
  homepage "https://github.com/kvndrsslr/kxdesk"
  url "https://github.com/kvndrsslr/kxdesk.git",
      tag:      "v0.1.23",
      revision: "f01b612bd8620c8aaad76e650ad8c9e8e3fbed7b"
  head "https://github.com/kvndrsslr/kxdesk.git", branch: "main"

  depends_on "zig" => :build
  depends_on :macos
  depends_on "terminal-notifier"

  def install
    system "zig", "build", "--prefix", prefix

    # The signing and launch scripts ride in the keg. Homebrew's install and
    # post-install steps are sandboxed with a temporary home and only the system
    # keychain, so neither can give the bundles the identity the grants outlive
    # an upgrade by; the service entry below runs in the user's session and does
    # it there. The `head` build is what has these scripts - the pinned tag
    # predates them.
    libexec.install "sign.sh", "service.sh"
    chmod 0755, libexec/"service.sh"

    # Both scripts are generated by the binary (`kxdesk completions <shell>`)
    # rather than shipped beside it, so what lands in the completion directories
    # cannot describe a command this build does not have. Default shells are
    # bash, zsh and fish; fish is not offered.
    #
    # This runs the binary at install time, so the pinned `url` above has to be a
    # tag that already has `completions` - v0.1.23 does not, and a non-HEAD
    # install from it would fail here. Bump the pin with the next release.
    generate_completions_from_executable(bin/"kxdesk", "completions", shells: [:bash, :zsh])
  end

  service do
    # The wrapper, not the bundle binary: it gives both bundles the machine's
    # stable identity and then execs the daemon, so launchd always starts an
    # application the grants will still recognise after the next upgrade.
    # macOS keys those grants - the one the event tap needs, and the grabber's
    # Input Monitoring - to the bundle identifier and that identity, where a
    # bare Mach-O's grant is keyed to a hash that every build changes.
    # `opt_prefix` is stable across `HEAD-<sha>` installs, which a plain
    # `Cellar` path would not be.
    run [opt_libexec/"service.sh"]
    keep_alive true
    process_type :interactive
    # Without these the daemon's output goes nowhere, and a failing command - a
    # key binding that could not be carried out, a bar update that was refused -
    # is silent.
    log_path var/"log/kxdesk.log"
    error_log_path var/"log/kxdesk.log"
  end

  def caveats
    <<~EOS
      The event tap needs one Accessibility grant, which macOS asks for on the first
      start: System Settings > Privacy & Security > Accessibility, "kxdesk".

      The service signs both bundles with a local certificate as it starts, so a
      grant survives an upgrade; start the service before installing the grabber.

      Home-row mods on the internal keyboard are the one part that needs root - a
      virtual HID driver to type a held key through, and a daemon to decide
      tap-versus-hold before the event tap sees the key. Both install with:

        sudo #{opt_bin}/kxdesk grabber install

      That daemon then needs Input Monitoring (System Settings > Privacy &
      Security) - seizing a keyboard is what tap-hold costs, and a root daemon
      cannot raise the approval dialog itself. Grant it to "kxdesk-grabber", then
      run `sudo kxdesk grabber install` once more to restart it.

      Nothing root-owned is Homebrew's, so no `sudo brew services` is involved:
      `kxdesk grabber uninstall` takes the daemon away again.
    EOS
  end

  test do
    # Every other command is answered by the daemon, and `brew test` does not
    # start one; the version, the help and the completions are the questions the
    # binary answers itself.
    assert_match(/\d+\.\d+\.\d+/, shell_output("#{bin}/kxdesk version"))
    assert_match("_kxdesk", shell_output("#{bin}/kxdesk completions zsh"))
    assert_match("_kxdesk", shell_output("#{bin}/kxdesk completions bash"))
    # The root half reports itself without needing root; installing it needs sudo.
    assert_match(/grabber: \w/, shell_output("#{bin}/kxdesk grabber status"))
  end
end
